export async function buildLegalPages(outDir) {
  const missing = unfilledPlaceholders();
  const isDraft = missing.length > 0;
  if (isDraft) {
    console.warn(`build-legal-pages: draft mode (noindex + banner) — fill these in src/pages/legal/content.js: ${missing.join(', ')}`);
  }
  for (const key of DOC_ORDER) {
    const dir = path.join(outDir, key);
    await mkdir(dir, { recursive: true });
    await writeFile(path.join(dir, 'index.html'), page(key, isDraft));
  }
  return DOC_ORDER.map((k) => `/${k}/`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const out = path.resolve(process.argv[2] || path.join(repoRoot, 'dist'));
  const written = await buildLegalPages(out);
  console.log(`build-legal-pages: wrote ${written.join(', ')} → ${out}`);
}
