// ============================================
// RELAY — LEGAL PAGES FOR THE MARKETING SITE
// ============================================
// Renders src/pages/legal/content.js — the same source the in-app #/terms,
// #/privacy, #/refunds and #/acceptable-use routes use — into the marketing
// site's page shell (site.css, header, footer), writing:
//
//   <outDir>/terms/index.html
//   <outDir>/privacy/index.html
//   <outDir>/refunds/index.html
//   <outDir>/acceptable-use/index.html
//
// build-pages.mjs calls this after copying site/ into dist/, so the words live
// in exactly one place. While any [BRACKETED] placeholder in content.js is
// unfilled, every page carries a draft banner and `noindex`; both disappear on
// their own once the entity details are filled in.
//
// Can also be run alone (e.g. to preview): node scripts/build-legal-pages.mjs [outDir]

import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { DOCS, DOC_ORDER, ENTITY, renderBlocks, unfilledPlaceholders } from '../src/pages/legal/content.js';

const docHref = (key) => `../${key}/`;

